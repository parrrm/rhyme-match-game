function syllables(word){
  let w = word.toLowerCase().replace(/qu/g, 'q').replace(/^y/, '');
  if (w.length <= 3) return 1;
  if (!/[^aeiouy]le$/.test(w)) w = w.replace(/(?:[^aeiouy]es|ed|e)$/, '');
  const m = w.match(/[aeiouy]{1,2}/g);
  return m ? m.length : 1;
}
