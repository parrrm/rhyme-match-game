function familyOf(word){
  const upper = word.toUpperCase();
  const families = wordToFamilies.get(upper);
  return families ? families[0] : (CORE_RHYME_FAMILIES[upper] || 'other:' + upper.slice(-3));
}
function loadTargetHistory(){
  try {
    const data = JSON.parse(localStorage.getItem('rhymeMatchTargets') || '{}');
    return { words: Array.isArray(data.words) ? data.words.slice(-RECENT_TARGET_LIMIT) : [], families: Array.isArray(data.families) ? data.families.slice(-RECENT_FAMILY_LIMIT) : [] };
  } catch(e){ return { words:[], families:[] }; }
}
let targetHistory = loadTargetHistory();
function rememberTarget(word){
  const upper = word.toUpperCase();
  targetHistory.words = [...targetHistory.words.filter(w => w !== upper), upper].slice(-RECENT_TARGET_LIMIT);
  targetHistory.families = [...targetHistory.families, familyOf(upper)].slice(-RECENT_FAMILY_LIMIT);
  try { localStorage.setItem('rhymeMatchTargets', JSON.stringify(targetHistory)); } catch(e){}
}
function pickTarget(){
  let choices = QUALITY_WORDS.filter(w => !targetHistory.words.includes(w) && !targetHistory.families.includes(familyOf(w)));
  if (!choices.length) choices = QUALITY_WORDS.filter(w => !targetHistory.words.includes(w));
  if (!choices.length) choices = QUALITY_WORDS;
  return choices[Math.floor(Math.random() * choices.length)];
}
