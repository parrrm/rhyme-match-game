const wordToFamilies = new Map();
RHYME_FAMILY_KEYS.forEach(family => {
  WORD_FAMILIES[family].forEach(word => {
    if (!wordToFamilies.has(word)) wordToFamilies.set(word, []);
    wordToFamilies.get(word).push(family);
  });
});

function familyOf(word){
  const upper = word.toUpperCase();
  const families = wordToFamilies.get(upper);
  return families ? families[0] : 'other:' + upper.slice(-3);
}

/* Known rhymes for a target (useful for host hints / judging aid).
   Returns words ordered easy -> hard, excluding the target itself. */
function getRhymes(target, { tier = null, limit = 0 } = {}){
  const fam = familyOf(target);
  const t = FAMILY_TIERS[fam];
  if (!t) return [];
  const order = tier ? [tier] : ['easy', 'medium', 'hard'];
  const out = order.flatMap(x => t[x]).filter(w => w !== target.toUpperCase());
  return limit ? out.slice(0, limit) : out;
}
/* true = known rhyme, false = not in bank (NOT proof it doesn't rhyme; host still judges). */
function isKnownRhyme(target, guess){
  const g = guess.toUpperCase(), t = target.toUpperCase();
  if (g === t) return false;
  const fam = familyOf(t);
  return (wordToFamilies.get(g) || []).includes(fam);
}

function loadTargetHistory(){
  try {
    const data = JSON.parse(localStorage.getItem('rhymeMatchTargets') || '{}');
    return {
      words: Array.isArray(data.words) ? data.words.slice(-RECENT_TARGET_LIMIT) : [],
      families: Array.isArray(data.families) ? data.families.slice(-RECENT_FAMILY_LIMIT) : []
    };
  } catch(e){ return { words:[], families:[] }; }
}
let targetHistory = loadTargetHistory();
function rememberTarget(word){
  const upper = word.toUpperCase();
  targetHistory.words = [...targetHistory.words.filter(w => w !== upper), upper].slice(-RECENT_TARGET_LIMIT);
  targetHistory.families = [...targetHistory.families, familyOf(upper)].slice(-RECENT_FAMILY_LIMIT);
  try { localStorage.setItem('rhymeMatchTargets', JSON.stringify(targetHistory)); } catch(e){}
}

/* Picks a random target.
   level: 'easy' (everyday 1-syllable words), 'normal' (default: easy + medium),
          'hard' (medium + hard).
   Picks the FAMILY first (so big families like AY don't dominate), then a word
   inside it, so every rhyme sound gets fair airtime. */
function pickTarget(level = 'normal'){
  const pool = TARGET_POOLS[level] || TARGET_POOLS.normal;
  const byFamily = new Map();
  pool.forEach(w => {
    if (targetHistory.words.includes(w)) return;
    const fam = familyOf(w);
    if (!byFamily.has(fam)) byFamily.set(fam, []);
    byFamily.get(fam).push(w);
  });
  let fams = Array.from(byFamily.keys()).filter(fam => !targetHistory.families.includes(fam));
  if (!fams.length) fams = Array.from(byFamily.keys());
  if (!fams.length) return pool[Math.floor(Math.random() * pool.length)];
  const fam = fams[Math.floor(Math.random() * fams.length)];
  const words = byFamily.get(fam);
  return words[Math.floor(Math.random() * words.length)];
}

