function pickTwistChallenge(target, history){
  const families = wordToFamilies.get(target) || [CORE_RHYME_FAMILIES[target]].filter(Boolean);
  const words = [...new Set(families.flatMap(f => WORD_FAMILIES[f] || []))].filter(w => w !== target);
  let eligible = TWIST_CHALLENGES.filter(challenge => words.filter(challenge.test).length >= 2);
  if (!eligible.length) return { id:'different-first-letter', text:`Use a rhyme that starts with a different letter than ${target}.` };
  const fresh = eligible.filter(challenge => !history.includes(challenge.id));
  if (fresh.length) eligible = fresh;
  const chosen = eligible[Math.floor(Math.random() * eligible.length)];
  return { id:chosen.id, text:chosen.text };
}


