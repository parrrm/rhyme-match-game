const QUALITY_WORDS = Array.from(new Set([...WORD_FAMILIES.core, ...Object.keys(WORD_FAMILIES)
  .filter(k => k !== 'core' && k !== 'longWords')
  .flatMap(k => WORD_FAMILIES[k])]));


const RECENT_TARGET_LIMIT = 18;
const RECENT_FAMILY_LIMIT = 5;
const wordToFamilies = new Map();
Object.entries(WORD_FAMILIES).forEach(([family, words]) => {
  if (family === 'core' || family === 'longWords') return;
  words.forEach(word => {
    if (!wordToFamilies.has(word)) wordToFamilies.set(word, []);
    wordToFamilies.get(word).push(family);
  });
});
